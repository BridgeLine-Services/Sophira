#!/usr/bin/env node
/**
 * PAGE CONFORMANCE — what each route actually is (2026-11-03, phase 2).
 *
 * docs/redesign-status.json says eight routes are partial and sixty-one are not started, which is
 * true but useless as a work order: it does not say what any given route is missing. This reads the
 * source and reports, per route, the things phase 2 requires and can be measured without a browser:
 * whether it uses the shared shell, how many h1s it renders, whether it has a main landmark, whether
 * a loading state and an empty state exist, whether it is a client component, and whether it uses
 * literal palette colours instead of semantic tokens.
 *
 * It measures source text, which has one real limit: an h1 or a landmark rendered by a shared child
 * component will not appear here. Those rows are marked "?" rather than "no" so the report never
 * claims a defect it cannot see.
 *
 * Usage: node scripts/page-conformance.mjs [--json]
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const APP = "src/app";
const LITERAL = /\b(?:bg|text|border|ring|from|to|via|divide|placeholder|shadow)-(?:slate|gray|zinc|neutral|stone)(?:-\d{2,3})?(?:\/\d{1,3})?\b/g;

const routeOf = (dir) =>
  "/" + relative(APP, dir).split("\\").join("/").replace(/\/?\([^)]*\)/g, "").replace(/\/+/g, "/").replace(/^\/$/, "").replace(/\/$/, "") || "/";

// A nested route inherits the nearest ancestor's loading.tsx, so counting files alone overstates gaps.
const hasLoading = (dir) => {
  let d = dir;
  while (d.startsWith(APP)) {
    if (existsSync(join(d, "loading.tsx"))) return true;
    if (d === APP) break;
    d = d.replace(/\/[^/]+$/, "");
  }
  return false;
};

const pages = [];
const walk = (dir) => {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) walk(full);
    else if (entry.name === "page.tsx") pages.push(full);
  }
};
walk(APP);
pages.sort();

const rows = pages.map((file) => {
  const src = readFileSync(file, "utf8");
  const dir = file.replace(/\/page\.tsx$/, "");
  const literals = (src.match(LITERAL) ?? []).length;
  const h1 = (src.match(/<h1[\s>]/g) ?? []).length;
  // A page that only redirects renders no content, so it needs no heading or landmark.
  const redirectOnly = /\bredirect\(/.test(src) && !/<[A-Za-z]/.test(src);
  const importsHeading = /from "(?:@\/|\.\.?\/)*components\/[^"]*"/.test(src);
  // AppShell renders both <h1>{title}</h1> and <main id="main-content">, so a shell page has a
  // heading and a landmark without writing either. Counted as inherited, not as its own.
  const shell = src.includes("AppShell");
  return {
    ownHeading: h1 > 0,
    route: routeOf(dir),
    file,
    shell,
    client: /^\s*["']use client["']/m.test(src),
    h1: shell ? 1 : h1,
    main: /<main[\s>]|role="main"/.test(src) || shell,
    loading: hasLoading(dir),
    redirectOnly,
    emptyState: src.includes("EmptyState") || /empty|nothing yet|No [a-z]+ yet/i.test(src),
    forms: (src.match(/<form[\s>]/g) ?? []).length,
    literals,
    // An h1 or landmark may live in a child component this scan cannot follow.
    uncertain: !src.includes("<h1") && importsHeading,
    // 2026-11-12: a thin wrapper can hand BOTH the heading and the <main> landmark to the
    // component it renders (a subject workspace, a legal document). Counting that as a
    // missing landmark was a false alarm the owner would have read as a real defect.
    landmarkDelegated: !/<main[\s>]|role="main"/.test(src) && !shell && !redirectOnly && /return\s*\(?\s*<[A-Z]/.test(src),
  };
});

const sum = (fn) => rows.filter(fn).length;
const summary = {
  routes: rows.length,
  shell: sum((r) => r.shell),
  client: sum((r) => r.client),
  noH1: sum((r) => r.h1 === 0 && !r.uncertain && !r.redirectOnly),
  h1Unknown: sum((r) => r.uncertain),
  multipleH1: sum((r) => r.h1 > 1),
  noMain: sum((r) => !r.main && !r.shell && !r.redirectOnly && !r.landmarkDelegated),
  landmarkDelegated: sum((r) => r.landmarkDelegated),
  noLoading: sum((r) => r.shell && !r.loading && !r.redirectOnly),
  noEmptyState: sum((r) => r.shell && !r.emptyState),
  literalColours: rows.reduce((n, r) => n + r.literals, 0),
};

if (process.argv.includes("--json")) {
  writeFileSync("docs/phase2-conformance.json", JSON.stringify({ summary, rows }, null, 2) + "\n");
}

const tick = (v) => (v ? "yes" : "**no**");
const lines = [
  "# PHASE 2 — ROUTE CONFORMANCE (generated)",
  "",
  "Generated by `node scripts/page-conformance.mjs` from the actual source. Do not edit by hand.",
  "",
  `**${summary.routes} routes** · ${summary.shell} use the shared shell · ${summary.client} are client components · ` +
    `${summary.noMain} without a landmark (${summary.landmarkDelegated} delegate it to a shared component) · ` +
    `${summary.noLoading} signed-in routes without a loading state · ${summary.noEmptyState} without an empty state · ` +
    `${summary.literalColours} literal palette colours.`,
  "",
  "\"no\" for a heading or landmark means the page's own source does not render one; it may still come",
  "from a child component the scan cannot follow, so a \"?\" marks that case instead of guessing.",
  "",
  "| Route | Shell | Client | h1 | main | loading | empty | forms | literals |",
  "|---|---|---|---|---|---|---|---|---|",
  ...rows.map(
    (r) =>
      `| \`${r.route}\`${r.redirectOnly ? " (redirect)" : ""} | ${tick(r.shell)} | ${tick(r.client)} | ${r.h1 === 0 && r.uncertain ? "?" : r.h1} | ${r.landmarkDelegated ? "?" : tick(r.main)} | ${tick(r.loading)} | ${tick(r.emptyState)} | ${r.forms} | ${r.literals} |`,
  ),
];
writeFileSync("docs/PHASE2_CONFORMANCE.md", lines.join("\n") + "\n");

console.log(`page-conformance: ${summary.routes} routes · ${summary.shell} shell · ${summary.noH1} without their own h1 · ${summary.noMain} without a landmark · ${summary.noLoading} signed-in without loading · ${summary.noEmptyState} without empty state`);
console.log("written: docs/PHASE2_CONFORMANCE.md" + (process.argv.includes("--json") ? " + docs/phase2-conformance.json" : ""));
